#!/bin/bash

# --- НАСТРОЙКИ ---
# Имя бакета, который НИКОГДА не нужно удалять (даже если он есть в списке)
PROTECTED_BUCKET="unn-cloud-bucket-svistunov"
# ----------------

# Получаем текущие ID облака и каталога из конфигурации yc
CLOUD_ID=$(yc config get cloud-id)
FOLDER_ID=$(yc config get folder-id)

# Проверяем, выбран ли каталог
if [ -z "$FOLDER_ID" ]; then
    echo "Ошибка: Не выбран каталог. Выполните 'yc config set folder-id <ID_каталога>' или 'yc init'."
    exit 1
fi

echo "===================================================="
echo " ⚠️  ВНИМАНИЕ! ОПАСНАЯ ОПЕРАЦИЯ ⚠️"
echo "===================================================="
echo "Вы собираетесь БЕЗВОЗВРАТНО удалить ВСЕ объекты и САМИ бакеты."
echo ""
echo "Облако:  $CLOUD_ID"
echo "Каталог: $FOLDER_ID"
echo "Исключение: Бакет '$PROTECTED_BUCKET' затронут НЕ будет."
echo "===================================================="
echo ""

# Запрашиваем подтверждение
read -p "Вы абсолютно уверены? Введите 'yes' для продолжения: " CONFIRM

# Проверяем, что ввел пользователь
if [ "$CONFIRM" != "yes" ]; then
    echo "Операция отменена. Скрипт остановлен."
    exit 0
fi

echo ""
echo "Получаем список бакетов..."

# Получаем список всех бакетов
BUCKETS=$(yc storage bucket list --format json | jq -r '.[].name')

if [ -z "$BUCKETS" ]; then
    echo "Бакеты в данном каталоге не найдены."
    exit 0
fi

# Проходимся циклом по каждому найденному бакету
for BUCKET_NAME in $BUCKETS; do
    echo "--------------------------------------------------"
    
    # Проверяем, не является ли текущий бакет защищенным
    if [ "$BUCKET_NAME" == "$PROTECTED_BUCKET" ]; then
        echo "🛡️  Пропуск: Найден защищенный бакет '$BUCKET_NAME'. Он не будет удален."
        continue # Прерываем текущую итерацию и переходим к следующему бакету
    fi
    
    echo "Начинаем работу с бакетом: $BUCKET_NAME"
    
    # 1. Очищаем бакет через AWS CLI
    echo " -> Удаление всех объектов..."
    aws s3 rm "s3://$BUCKET_NAME" --recursive --endpoint-url="https://storage.yandexcloud.net"
    
    # 2. Удаляем сам пустой бакет через yc
    echo " -> Удаление контейнера бакета..."
    yc storage bucket delete "$BUCKET_NAME"
    
    echo "✅ Бакет $BUCKET_NAME полностью удален."
done

echo "=================================================="
echo "Готово! Все бакеты (кроме защищенных) удалены."